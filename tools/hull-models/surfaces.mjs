/**
 * Every navy's surfaces, drawn once (#1811).
 *
 *   node tools/hull-models/surfaces.mjs   # writes packages/frontend/src/assets/surface/<navy>-<material>.png
 *                                         # and packages/frontend/src/game/navySurfaces.generated.ts
 *
 * A surface is a navy material's, so it is in no GLB: the client samples it
 * by a fragment's place on the model (packages/frontend/src/game/navySurface.ts)
 * and finds it by the navy and the material's own name, which every model of
 * the navy already carries. So no model is re-exported to wear one, and a
 * navy without a `SURFACE` export wears none.
 *
 * Each image is the committed output of one row of the navy's `SURFACE`
 * table in its faction module, drawn by surface.mjs `drawSurface` with no
 * random number in it. What the client must know to read an image is how
 * many metres it spans, what slope a full byte stands for and where its
 * height's mean lies, and those are the draw's own, so they are written
 * beside the images as a generated module rather than typed a second time.
 * check.mjs redraws every surface and holds both to the draw.
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';
import { SURFACE_DIR, drawSurface } from './surface.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const repo = resolve(here, '../..');

/** The module the client reads each surface's scale from. */
export const SURFACE_FILE = join(repo, 'packages/frontend/src/game/navySurfaces.generated.ts');

/** Each navy's `SURFACE`, by its name, read off the faction modules. */
export async function navySurfaces() {
  const out = new Map();
  for (const file of readdirSync(join(here, 'factions')).sort()) {
    if (!file.endsWith('.mjs')) continue;
    const mod = await import(pathToFileURL(join(here, 'factions', file)).href);
    if (mod.SURFACE) out.set(mod.SURFACE.name, mod.SURFACE);
  }
  return out;
}

/** The image a navy's material is committed as, by both names. */
export const surfaceName = (navy, material) => `${navy}-${material}`;

/** The committed path of a surface by its name. */
export const surfacePath = (name) => join(repo, SURFACE_DIR, `${name}.png`);

/** Every surface drawn: `[name, navy, material, drawn]` rows, in table order. */
export async function drawAll() {
  const rows = [];
  for (const [navy, surface] of await navySurfaces())
    for (const [material, table] of Object.entries(surface.materials))
      rows.push({ name: surfaceName(navy, material), navy, material, drawn: drawSurface(table) });
  return rows;
}

/** The generated module's text for the rows `drawAll` returns. */
export async function renderSource(rows) {
  const navies = new Map();
  for (const { navy, material, drawn } of rows) {
    if (!navies.has(navy)) navies.set(navy, []);
    navies
      .get(navy)
      .push(
        `${material}: { tileM: ${drawn.tileM}, slope: ${drawn.slope}, ` +
          `reliefM: ${drawn.reliefM.toFixed(4)}, mean: ${drawn.mean.toFixed(4)} }`
      );
  }
  const src = `/**
 * GENERATED by tools/hull-models/surfaces.mjs from each navy's \`SURFACE\`
 * table (tools/hull-models/factions/). Do not edit: redraw, and
 * tools/hull-models/check.mjs holds this file and the images to the draw.
 *
 * What the conn view must know to read a navy material's surface image
 * (navySurface.ts): \`tileM\` the metres one image spans, \`slope\` the rise
 * a full byte of its red and green stands for, \`reliefM\` the height its
 * blue spans and \`mean\` where that blue's mean lies, 0 to 1.
 */
export interface NavySurfaceScale {
  readonly tileM: number;
  readonly slope: number;
  readonly reliefM: number;
  readonly mean: number;
}

/** Each navy's surfaces by sheet name, then by the material's own name. */
export const NAVY_SURFACE_SCALES: Readonly<Record<string, Readonly<Record<string, NavySurfaceScale>>>> = {
${[...navies].map(([navy, lines]) => `  ${navy}: {\n    ${lines.join(',\n    ')},\n  },`).join('\n')}
};
`;
  const options = (await prettier.resolveConfig(SURFACE_FILE)) ?? {};
  return prettier.format(src, { ...options, filepath: SURFACE_FILE });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(repo, SURFACE_DIR), { recursive: true });
  const rows = await drawAll();
  for (const { name, drawn } of rows) {
    writeFileSync(surfacePath(name), drawn.png);
    console.log(
      `${name}.png: ${drawn.size}² over ${drawn.tileM} m, ${drawn.png.length} bytes, ` +
        `${(drawn.reliefM * 100).toFixed(1)} cm of relief, mean ${drawn.mean.toFixed(3)}` +
        (drawn.clipped ? `, ${drawn.clipped} slopes CLIPPED at ${drawn.slope}` : '')
    );
  }
  writeFileSync(SURFACE_FILE, await renderSource(rows));
}
